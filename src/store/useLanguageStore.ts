// Helper function to get nested translation
function getNestedValue(obj: Record<string, string>, key: string): string {
  const value = obj[key];
  if (value) return value;
  
  // Try to find a partial match
  const parts = key.split('.');
  let current: string | Record<string, string> = obj;
  
  for (const part of parts) {
    if (typeof current === 'string') return current;
    if (current[part] === undefined) return key;
    current = current[part] as string | Record<string, string>;
  }
  
  return typeof current === 'string' ? current : key;
}

export const useLanguageStore = create<LanguageState>()(
  persist(
    (set, get) => ({
      language: 'en',
      setLanguage: (language) => set({ language }),
      t: (key) => {
        const state = get();
        const lang = state.language;
        const translation = translations[lang] || translations.en;
        return getNestedValue(translation, key) || key;
      },
    }),
    {
      name: 'webfinder-language',
      storage: createJSONStorage(() => localStorage),
      partialize: (state) => ({ language: state.language }),
    }
  )
);
